-- Application schema. Users and sessions live in the `neon_auth` schema,
-- which Neon Auth manages; this file only creates the app's own tables.

create table guestbook (
  id bigint generated always as identity primary key,
  -- Public identifier used by the UI (nanoid).
  cid text not null unique,
  -- Null only for migrated entries whose author has not signed in yet.
  user_id uuid references neon_auth."user" (id) on delete set null,
  -- Set for migrated entries until the author signs in with a verified
  -- matching email and claims them; then cleared.
  legacy_owner_email text,
  name text not null,
  avatar text,
  comment text not null check (char_length(comment) between 1 and 2000),
  created_at timestamptz not null default now(),
  constraint guestbook_has_owner check (user_id is not null or legacy_owner_email is not null)
);

create index guestbook_created_at_idx on guestbook (created_at desc);
create index guestbook_user_id_idx on guestbook (user_id);
create index guestbook_legacy_owner_email_idx on guestbook (legacy_owner_email)
  where legacy_owner_email is not null;

create table chatbot_conversations (
  id bigint generated always as identity primary key,
  -- Random per-visit id generated by the client (nanoid).
  chat_id text not null unique,
  messages jsonb not null check (jsonb_typeof(messages) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
